"""Aggregate scored runs into docs/RESULTS.md.

Every number is mean ± spread over repetitions, never a single figure (SCORING.md §6).
Degraded runs and runs with an evidence-layer error are excluded from headline numbers
and listed separately (§5).

    python -m eval.report                       # runtime/eval/results.jsonl
    python -m eval.report --in runtime/eval/dev3.jsonl --out -
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _ms(xs: list[float]) -> str:
    if not xs:
        return "–"
    m = statistics.fmean(xs)
    sd = statistics.pstdev(xs) if len(xs) > 1 else 0.0
    return f"{m:.2f} ± {sd:.2f}"


def _pct(xs: list[bool]) -> str:
    return f"{100 * sum(xs) / len(xs):.0f}% ({sum(xs)}/{len(xs)})" if xs else "–"


#: Errors raised by the engine's own logic, not by infrastructure. These are results about
#: the engine and are scored as failures on their first attempt; a later retry of the same
#: key is listed separately and never substituted (no survivorship bias).
ENGINE_ERRORS = ("hypothesize produced",)


def engine_failures(errors: list[dict]) -> dict[str, dict]:
    """First engine-originated error per key, as a scored abstention."""
    out: dict[str, dict] = {}
    for e in errors:
        if e["key"] in out or not any(m in e.get("error", "") for m in ENGINE_ERRORS):
            continue
        fault = e["key"].split("|")[0]
        decoys_on = "decoys=on" in e["key"]
        out[e["key"]] = {"key": e["key"], "engine_failure": True, "score": {
            "fault_id": fault, "outcome": "INSUFFICIENT_EVIDENCE", "rca": 0.0,
            "proximate_correct": False, "originating_correct": False,
            "decoy_blamed": False, "abstained": True, "abstention_correct": fault == "F-07",
            "decoys": ["(decoys on)"] if decoys_on else [], "claims_total": 0,
            "claims_stripped": 0, "mttd_s": None, "mttr_diagnosis_s": None, "cost_usd": 0.0,
            "error": e["error"], "leader": f"(engine failure: {e['error'][:80]})"}}
    return out


def build(rows: list[dict], errors: list[dict] | None = None) -> str:
    failed = engine_failures(errors or [])
    retried = [r for r in rows if r["key"] in failed]
    rows = [r for r in rows if r["key"] not in failed] + list(failed.values())
    scored = [r["score"] for r in rows]
    excluded = [s for s in scored if s.get("degraded") or (s.get("error") or "").startswith(("ConnectError", "HTTP"))]
    head = [s for s in scored if s not in excluded and s.get("outcome") != "NOT_DETECTED"]
    undetected = [s for s in scored if s.get("outcome") == "NOT_DETECTED"]
    solvable = [s for s in head if s["fault_id"] != "F-07"]
    f07 = [s for s in head if s["fault_id"] == "F-07"]

    claims = sum(s.get("claims_total") or 0 for s in head)
    stripped = sum(s.get("claims_stripped") or 0 for s in head)
    decoy_runs = [s for s in head if s.get("decoys")]

    commits = sorted({r.get("commit") for r in rows if r.get("commit")})
    lines = [
        "# Results",
        "",
        f"Engine commit: {', '.join(commits) or 'unknown'}. Generated by `python -m eval.report` "
        "from `runtime/eval/results.jsonl`.",
        "",
        "**What was run.** 6 faults x 3 repetitions x 2 decoy conditions (decoys on / off) = 36 "
        "runs, plus 3 runs of F-07 (the abstention case). Each run: reset to baseline, wait for "
        "a clean baseline, inject, let the burn-rate detector open the incident on its own, "
        "investigate with no human input, score against the ground truth the injector wrote to "
        "`sherlog_truth`. Models: gpt-4.1-mini-2025-04-14 (triage, gather) and "
        "gpt-4.1-2025-04-14 (hypothesize, assess, critic, report).",
        "",
        "**How it is scored.** Every metric is computed by code (docs/SCORING.md, including its "
        "dated revision log, all written before this matrix ran). RCA@1 requires the leading "
        "hypothesis to name the right originating component AND the fault's mechanism AND an "
        "accepted fault class; abstaining on a solvable fault scores 0. Every number is mean +/- "
        "standard deviation over runs, never a single best run.",
        "",
        "**Read with docs/BUILD_LOG.md section 4**, which names the open issues behind most "
        "misses (O1 rival ties under the evidence caps, O2 vague mechanism wording, O3 "
        "proximate-service ambiguity, O8 load-dependent detection of F-03).",
        "",
        f"{len(scored)} runs: {len(head)} scored, {len(undetected)} not detected, "
        f"{len(excluded)} excluded (degraded / evidence-layer error).",
        "",
        "## Headline",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Detection rate (fault injected -> SLO alert within 8 min) | "
        f"{_pct([s.get('outcome') != 'NOT_DETECTED' for s in scored if s not in excluded])} |",
        f"| RCA accuracy@1 end-to-end, F-01..F-06 (undetected runs count as misses) | "
        f"{_ms([s['rca'] for s in scored if s not in excluded and s['fault_id'] != 'F-07'])} |",
        f"| RCA accuracy@1 of investigated runs, F-01..F-06 | {_ms([s['rca'] for s in solvable])} |",
        f"| Service localisation | {_pct([bool(s['proximate_correct']) for s in head])} |",
        f"| Origin localisation | {_pct([bool(s['originating_correct']) for s in head])} |",
        f"| Abstention correctness (abstain on F-07, answer on the rest) | {_pct([bool(s['abstention_correct']) for s in head])} |",
        f"| Correct abstention on F-07 | {_pct([bool(s['abstained']) for s in f07])} |",
        f"| Decoy resistance (runs with decoys) | {_pct([not s['decoy_blamed'] for s in decoy_runs])} |",
        f"| Claims stripped by citation verification | {f'{100 * stripped / claims:.1f}% ({stripped}/{claims})' if claims else '–'} |",
        f"| MTTD, injection -> detection (s) | {_ms([s['mttd_s'] for s in head if s.get('mttd_s') is not None])} |",
        f"| MTTR-diagnosis, detection -> verdict (s) | {_ms([s['mttr_diagnosis_s'] for s in head if s.get('mttr_diagnosis_s') is not None])} |",
        f"| Cost per investigation (USD) | {_ms([s['cost_usd'] for s in head])} |",
        "",
        "## Per fault",
        "",
        "| Fault | Runs | RCA@1 | Service | Origin | Outcomes |",
        "|---|---|---|---|---|---|",
    ]
    by_fault: dict[str, list[dict]] = defaultdict(list)
    for s in head:
        by_fault[s["fault_id"]].append(s)
    for f in sorted(by_fault):
        ss = by_fault[f]
        outcomes = defaultdict(int)
        for s in ss:
            outcomes[s["outcome"]] += 1
        lines.append(
            f"| {f} | {len(ss)} | {_ms([s['rca'] for s in ss])} | "
            f"{_pct([bool(s['proximate_correct']) for s in ss])} | "
            f"{_pct([bool(s['originating_correct']) for s in ss])} | "
            + ", ".join(f"{k} {v}" for k, v in sorted(outcomes.items())) + " |")
    lines += ["", "## Every run", "", "| Run | Outcome | RCA | Leading hypothesis |", "|---|---|---|---|"]
    for r in rows:
        s = r["score"]
        lines.append(f"| {r['key'].replace('|', ' / ')} | {s.get('outcome')} | {s.get('rca')} | "
                     f"{(s.get('leader') or '').replace('|', '/')} |")
    if failed:
        lines += ["", "## Engine failures and their retries",
                  "", "Scored above as failures on the first attempt. The harness retried "
                  "them; the retry outcome is shown here for information and is NOT counted.",
                  "", "| Run | First attempt | Retry outcome | Retry RCA |", "|---|---|---|---|"]
        rmap = {r["key"]: r["score"] for r in retried}
        for k, f in failed.items():
            rs = rmap.get(k, {})
            lines.append(f"| {k.replace('|', ' / ')} | {f['score']['error'][:70].replace('|', '/')} | {rs.get('outcome', '(not retried)')} "
                         f"| {rs.get('rca', '–')} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="src", default=str(ROOT / "runtime" / "eval" / "results.jsonl"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "RESULTS.md"))
    args = ap.parse_args()
    rows = [json.loads(line) for line in Path(args.src).read_text(encoding="utf-8").splitlines()
            if line.strip()]
    err_path = Path(args.src).with_name(Path(args.src).stem + ".errors.jsonl")
    errors = ([json.loads(line) for line in err_path.read_text(encoding="utf-8").splitlines()
               if line.strip()] if err_path.exists() else [])
    text = build(rows, errors)
    if args.out == "-":
        print(text)
    else:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
